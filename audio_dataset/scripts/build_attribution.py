#!/usr/bin/env python3
"""
SonicSentinel AI -- attribution + licence summary generator.

Owner: omar (data sourcing).

WHY THIS EXISTS
---------------
Most of the real audio in this project is Freesound audio used under CC-BY-3.0.
That licence is only valid if the author is credited and the licence named -- a
dataset that uses CC-BY audio without attribution is not licensed at all, it is
just copied. So the credit file is not decoration: it is the thing that makes the
corpus legal to publish.

It also produces a licence summary, so the report's claim "no non-commercial audio
anywhere" can be read off a generated file rather than asserted by hand.

INPUT
-----
Any manifest-shaped CSV with the frozen columns. Defaults to the assembled
`audio_dataset/manifest.csv` if it exists, otherwise the real-audio source rows.
Only rows with a real (non-synthetic) provenance are credited; synthetic rows are
listed separately as project-generated.

OUTPUT
------
  audio_dataset/licences/ATTRIBUTION.md      -- per-author credits, CC-BY compliant
  audio_dataset/licences/LICENCE_SUMMARY.md  -- licence mix + non-commercial check

Usage
-----
    .venv/bin/python audio_dataset/scripts/build_attribution.py
    .venv/bin/python audio_dataset/scripts/build_attribution.py --manifest <csv>
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter, defaultdict
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
AUDIO_DATASET = SCRIPT_DIR.parent
REPO_ROOT = AUDIO_DATASET.parent

DEFAULT_MANIFEST_CANDIDATES = [
    AUDIO_DATASET / "manifest.csv",
    AUDIO_DATASET / "manifests" / "fsd50k_real_rows.csv",
]
DEFAULT_ATTRIBUTION = AUDIO_DATASET / "licences" / "ATTRIBUTION.md"
DEFAULT_SUMMARY = AUDIO_DATASET / "licences" / "LICENCE_SUMMARY.md"

FREESOUND_PROFILE = "https://freesound.org/people/{author}/"
FREESOUND_SOUND = "https://freesound.org/s/{fid}/"


def load(path: Path) -> tuple[list[str], list[dict]]:
    with path.open(newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        rows = list(reader)
        return reader.fieldnames or [], rows


def is_synthetic(row: dict) -> bool:
    src = (row.get("source") or "").lower()
    return "synthesis" in src or (row.get("audio_provenance") or "").lower() == "synthetic"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, default=None,
                    help="manifest-shaped CSV (default: assembled manifest, else the real source rows)")
    ap.add_argument("--attribution", type=Path, default=DEFAULT_ATTRIBUTION)
    ap.add_argument("--summary", type=Path, default=DEFAULT_SUMMARY)
    args = ap.parse_args(argv)

    path = args.manifest
    if path is None:
        for cand in DEFAULT_MANIFEST_CANDIDATES:
            if cand.exists():
                path = cand
                break
    if path is None or not path.exists():
        print("ERROR: no manifest found to build attribution from", file=sys.stderr)
        return 2
    print(f"reading {path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path}")

    _cols, rows = load(path)
    real = [r for r in rows if not is_synthetic(r)]
    synth = [r for r in rows if is_synthetic(r)]

    # ---- per-author credit table -------------------------------------------------
    by_author: dict[str, list[dict]] = defaultdict(list)
    for r in real:
        by_author[(r.get("author") or "unknown").strip()].append(r)

    lic_counter = Counter((r.get("licence") or "").strip() for r in real)
    unknown_lic = [r for r in real if not (r.get("licence") or "").strip()]

    lines = [
        "# Audio attribution and licence record",
        "",
        "SonicSentinel AI -- generated by `audio_dataset/scripts/build_attribution.py`.",
        "**Do not edit by hand**; regenerate after any change to the manifest.",
        "",
        f"Real recordings credited: **{len(real)}** across **{len(by_author)}** authors.",
        f"Project-generated (synthetic) recordings: **{len(synth)}** "
        "(created by this project's own code, CC0-1.0 -- no third-party rights).",
        "",
        "Every real recording below is used under a licence that permits redistribution",
        "and reuse. Where the licence is CC-BY-3.0 the author is credited, as that licence",
        "requires. Nothing here is used under a non-commercial licence.",
        "",
        "---",
        "",
        "## Credits",
        "",
    ]
    for author in sorted(by_author, key=lambda a: (-len(by_author[a]), a)):
        items = by_author[author]
        lics = sorted({(r.get("licence") or "").strip() for r in items})
        lines.append(f"### {author}  ({len(items)} recording(s))")
        lines.append("")
        lines.append(f"- Freesound profile: {FREESOUND_PROFILE.format(author=author)}")
        lines.append(f"- Licence(s): {', '.join(lics)}")
        shown = sorted(items, key=lambda r: r.get("audio_id", ""))[:6]
        listed = "; ".join(
            f"[{r.get('freesound_id') or r.get('audio_id')}]"
            f"({FREESOUND_SOUND.format(fid=r.get('freesound_id')) if r.get('freesound_id') else r.get('source_url','')})"
            for r in shown
        )
        extra = f" and {len(items) - len(shown)} more" if len(items) > len(shown) else ""
        lines.append(f"- Clips{extra}: {listed}")
        lines.append("")

    lines += [
        "---",
        "",
        "## Project-generated audio",
        "",
        "The following classes contain recordings generated by this project's own code",
        "(`data/generate_corpus.py`). They are not field recordings and are never presented",
        "as such. They are CC0-1.0 by the project's own dedication.",
        "",
    ]
    synth_by_src = Counter((r.get("source") or "").split(":")[0] for r in synth)
    for src, n in sorted(synth_by_src.items()):
        lines.append(f"- `{src}`: {n} recording(s)")
    lines.append("")

    args.attribution.parent.mkdir(parents=True, exist_ok=True)
    args.attribution.write_text("\n".join(lines), encoding="utf-8")

    # ---- licence summary ----------------------------------------------------------
    sm = [
        "# Licence summary",
        "",
        "Generated by `audio_dataset/scripts/build_attribution.py`. Read this file to check",
        "the report's licensing claims rather than trusting them.",
        "",
        "## Real recordings by licence",
        "",
        "| Licence | Count |",
        "|---|---|",
    ]
    for lic, n in lic_counter.most_common():
        sm.append(f"| {lic or '(blank)'} | {n} |")
    sm += [
        "",
        "## Integrity checks",
        "",
        f"- real recordings with a blank licence: **{len(unknown_lic)}** "
        f"({'PASS' if not unknown_lic else 'FAIL -- every file must carry a licence'})",
        f"- non-commercial licences present: **{sum(n for l, n in lic_counter.items() if 'NC' in l.upper() or 'NONCOMMERCIAL' in l.upper())}** "
        "(must be 0 -- the SRS does not allow non-commercial audio)",
        f"- distinct licences in use: **{len(lic_counter)}**",
        "",
        "## Sources",
        "",
        "- Real audio: **FSD50K** (Fonseca et al.), a corpus of Freesound clips whose",
        "  per-clip licences are recorded in `audio_dataset/manifests/fsd50k_real_rows.csv`.",
        "  Clip pages: https://freesound.org",
        "- Synthetic audio: generated by this project; see `audio_dataset/DATA_DICTIONARY.md`.",
        "",
    ]
    args.summary.write_text("\n".join(sm), encoding="utf-8")

    print(f"wrote {args.attribution}  ({len(by_author)} authors, {len(real)} credited recordings)")
    print(f"wrote {args.summary}  (licences: {dict(lic_counter)})")
    if unknown_lic:
        print(f"WARNING: {len(unknown_lic)} real recordings have a blank licence", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
