"""Dataset quality report (SRS deliverable 3).

    python tools/dataset_quality_report.py

Combines the manifest with the quality verdict the app's own preprocessor gave every clip
(data/cache/pre16k/index.csv, written by python -m python_models.preprocess_cache).
Writes reports/dataset_quality.json and reports/DATASET_QUALITY.md.
"""

from __future__ import annotations

import csv
import json
import statistics
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERDICTS = ["Good", "Acceptable", "Poor", "Unusable"]


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def main() -> None:
    rows = read_csv(ROOT / "audio_dataset" / "manifest.csv")
    quality = {r["audio_id"]: r for r in read_csv(ROOT / "data" / "cache" / "pre16k" / "index.csv")}
    classes = sorted({r["class_label"] for r in rows})

    per_class = defaultdict(Counter)
    per_split = defaultdict(Counter)
    durations = defaultdict(list)
    for r in rows:
        q = quality.get(r["audio_id"], {})
        verdict = q.get("quality") or "not measured"
        if q.get("rejected") == "True":
            verdict = "Unusable"
        per_class[r["class_label"]][verdict] += 1
        per_split[r["dataset_split"]][verdict] += 1
        durations[r["class_label"]].append(float(r["duration_sec"]))

    doc = {
        "clips": len(rows),
        "measured": sum(1 for r in rows if r["audio_id"] in quality),
        "verdicts": dict(sum((per_class[c] for c in classes), Counter())),
        "per_class": {c: dict(per_class[c]) for c in classes},
        "per_split": {s: dict(per_split[s]) for s in ("train", "val", "test")},
        "duration_sec": {c: {"min": round(min(d), 2), "median": round(statistics.median(d), 2),
                             "max": round(max(d), 2)} for c, d in durations.items()},
        "sample_rates": dict(Counter(r["sampling_rate"] for r in rows).most_common()),
        "channels": dict(Counter(r["channels"] for r in rows).most_common()),
        "environments": dict(Counter(r["recording_environment"] for r in rows).most_common()),
        "sources": {"real": sum(1 for r in rows if not r["source"].startswith("procedural")),
                    "generated": sum(1 for r in rows if r["source"].startswith("procedural"))},
    }
    (ROOT / "reports" / "dataset_quality.json").write_text(json.dumps(doc, indent=2) + "\n")

    def table(counter_by: dict, keys: list[str]) -> list[str]:
        cols = VERDICTS + (["not measured"] if any("not measured" in v for v in counter_by.values()) else [])
        out = ["| | " + " | ".join(cols) + " |", "|---|" + "---:|" * len(cols)]
        for k in keys:
            out.append(f"| {k} | " + " | ".join(str(counter_by[k].get(v, 0)) for v in cols) + " |")
        return out

    md = [
        "# Dataset quality report",
        "",
        "Generated by `tools/dataset_quality_report.py`. Every clip was run through the app's",
        "own preprocessing (`python -m python_models.preprocess_cache`), which gives each one the",
        "same quality verdict an upload would get. Integrity (hashes, counts, split, licences) is",
        "checked separately by `audio_dataset/scripts/verify_dataset.py --strict`.",
        "",
        f"{doc['clips']:,} original clips, {doc['measured']:,} measured: " + ", ".join(
            f"{doc['verdicts'].get(v, 0):,} {v}" for v in VERDICTS) + ".",
        f"{doc['sources']['real']:,} are real recordings and {doc['sources']['generated']:,} were generated.",
        "",
        "## Quality verdict per class",
        "",
        *table(per_class, classes),
        "",
        "## Quality verdict per split",
        "",
        *table(per_split, ["train", "val", "test"]),
        "",
        "## Duration per class (seconds)",
        "",
        "| Class | Min | Median | Max |",
        "|---|---:|---:|---:|",
        *[f"| {c} | {d['min']} | {d['median']} | {d['max']} |" for c, d in doc["duration_sec"].items()],
        "",
        "## Formats",
        "",
        "Sample rates: " + ", ".join(f"{k} Hz ({v})" for k, v in doc["sample_rates"].items()) + ".",
        "Channels: " + ", ".join(f"{k} ({v})" for k, v in doc["channels"].items()) + ".",
        "Recording environment: " + ", ".join(f"{k} ({v})" for k, v in doc["environments"].items()) + ".",
        "",
    ]
    (ROOT / "reports" / "DATASET_QUALITY.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:10]))


if __name__ == "__main__":
    main()
